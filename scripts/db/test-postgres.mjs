import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export function testDatabaseUrl(source, database) {
  let url;
  try { url = new URL(source); } catch { throw new Error('ZEUS_TEST_DATABASE_URL must be a PostgreSQL URL.'); }
  if (!['postgres:', 'postgresql:'].includes(url.protocol) ||
      !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname) || url.search || url.hash) {
    throw new Error('Database tests require a loopback PostgreSQL URL without query parameters.');
  }
  if (!/^zeus_test_[a-f0-9]{24}$/u.test(database)) {
    throw new Error('Refusing a database name not generated by the test runner.');
  }
  url.pathname = `/${database}`;
  return url;
}

async function main() {
  const databaseUrl = process.env.ZEUS_TEST_DATABASE_URL;
  const probe = testDatabaseUrl(databaseUrl, `zeus_test_${randomBytes(12).toString('hex')}`);
  const source = new URL(databaseUrl);
  const envelopeKey = randomBytes(32).toString('hex');
  const secrets = [databaseUrl, source.password, decodeURIComponent(source.password), envelopeKey]
    .filter(Boolean).sort((a, b) => b.length - a.length);
  const safeOutput = (text) => secrets.reduce((value, secret) => value.replaceAll(secret, '<REDACTED>'), text);

  async function run(command, args, env, quiet = false) {
    await new Promise((resolve, reject) => {
      const child = spawn(command, args, { cwd: root, env, stdio: ['ignore', 'pipe', 'pipe'] });
      let output = '';
      child.stdout.on('data', (chunk) => { output += chunk; });
      child.stderr.on('data', (chunk) => { output += chunk; });
      child.on('error', () => reject(new Error(`${command} could not start.`)));
      child.on('close', (code) => {
        if (!quiet || code !== 0) process.stdout.write(safeOutput(output));
        if (code === 0) resolve();
        else reject(new Error(`${command} failed (exit ${code}).`));
      });
    });
  }

  const pgEnv = {
    ...process.env,
    PGHOST: probe.hostname.replace(/^\[|\]$/gu, ''),
    PGPORT: probe.port || '5432',
    PGUSER: decodeURIComponent(probe.username),
    PGPASSWORD: decodeURIComponent(probe.password),
    PGDATABASE: decodeURIComponent(source.pathname.slice(1)) || 'postgres',
    PGCONNECT_TIMEOUT: '10'
  };
  delete pgEnv.PGSERVICE;
  delete pgEnv.PGOPTIONS;
  const psql = (args, env = pgEnv) => run('psql', ['--no-psqlrc', '--set', 'ON_ERROR_STOP=1', ...args], env, true);
  const targets = (await readdir(path.join(root, 'apps/zeus-api/tests')))
    .filter((name) => name.endsWith('_postgres.rs')).sort().map((name) => name.slice(0, -3));

  await run('cargo', ['test', '--locked', '--quiet', '-p', 'zeus-api', '--tests', '--no-run'], process.env);
  for (const target of targets) {
    const database = `zeus_test_${randomBytes(12).toString('hex')}`;
    const url = testDatabaseUrl(databaseUrl, database);
    secrets.push(url.toString());
    await psql(['--command', `CREATE DATABASE ${database}`]);
    try {
      await psql(['--file', 'scripts/db/bootstrap-roles.sql'], { ...pgEnv, PGDATABASE: database });
      process.stdout.write(`PostgreSQL integration: ${target}\n`);
      await run('cargo', ['test', '--locked', '-p', 'zeus-api', '--test', target, '--', '--ignored', '--test-threads=1'], {
        ...process.env,
        ZEUS_TEST_DATABASE_URL: url.toString(),
        ZEUS_TEST_ENVELOPE_KEY: envelopeKey,
        RUST_TEST_THREADS: '1'
      });
    } finally {
      // Only this invocation's random database is ever removed. No API uses it.
      await psql(['--command', `DROP DATABASE ${database} WITH (FORCE)`]);
    }
  }
  process.stdout.write(`PostgreSQL integration targets passed: ${targets.length}; temporary databases removed.\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
